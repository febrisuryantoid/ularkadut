export function resolveSkinConfig(
  skinId: SnakeSkinId,
  customSkin?: CustomSkinConfig
): SnakeSkinConfig {
  const base = SNAKE_SKIN_CATALOG[skinId] || SNAKE_SKIN_CATALOG.classic;
  if (skinId !== 'custom_sultan' || !customSkin) {
    return base;
  }
  return {
    ...base,
    name: customSkin.customName || base.name,
    headColor: customSkin.headColor,
    bodyPrimary: customSkin.bodyPrimary,
    bodySecondary: customSkin.bodySecondary,
    bellyColor: customSkin.bellyColor,
    eyeColor: customSkin.eyeColor,
    pupilColor: customSkin.pupilColor,
    glowColor: customSkin.glowColor,
    sparkleColor: customSkin.sparkleColor,
    pattern: customSkin.pattern,
    wings: customSkin.wings,
    headgear: customSkin.headgear,
    hasCrown: customSkin.headgear === 'crown',
    tail: customSkin.tail,
    tierVFX: {
      auraIntensity: 1.0,
      particleType: customSkin.particleType,
      trailLength: 8,
      shimmerRate: 2.8,
    },
  };
}

