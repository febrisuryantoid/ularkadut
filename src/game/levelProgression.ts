export function getLevelConfig(difficulty: DifficultyLevel, levelNumber: number): LevelConfig {
  const list = LEVEL_PROGRESSION[difficulty] || LEVEL_PROGRESSION.easy;
  const clamped = Math.max(1, Math.min(MAX_LEVELS_PER_DIFFICULTY, Math.floor(levelNumber)));
  return list[clamped - 1] || list[0];
}

export function calculateLevelStars(score: number, targetScore: number, cutCount: number): number {
  if (score < targetScore) return 0;
  if (score >= Math.round(targetScore * 1.25) || cutCount === 0) {
    return 3;
  }
  if (score >= Math.round(targetScore * 1.1)) {
    return 2;
  }
  return 2;
}
